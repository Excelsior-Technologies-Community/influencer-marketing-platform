CREATE TABLE IF NOT EXISTS campaign_funding (
 id CHAR(36) PRIMARY KEY,campaign_id CHAR(36) NOT NULL UNIQUE,
 amount_minor BIGINT UNSIGNED NOT NULL,currency CHAR(3) NOT NULL DEFAULT 'INR',
 provider_key_id VARCHAR(80) NOT NULL,provider_order_id VARCHAR(80) NULL UNIQUE,
 status VARCHAR(24) NOT NULL DEFAULT 'CREATING',captured_payment_id VARCHAR(80) NULL UNIQUE,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 FOREIGN KEY(campaign_id) REFERENCES campaigns(id),
 CHECK(amount_minor>=100 AND currency='INR'),
 CHECK(status IN ('CREATING','SETUP_REVIEW','PENDING','SUCCEEDED'))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS campaign_payment_attempts (
 provider_payment_id VARCHAR(80) PRIMARY KEY,funding_id CHAR(36) NOT NULL,
 status VARCHAR(24) NOT NULL,amount_minor BIGINT UNSIGNED NOT NULL,currency CHAR(3) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 FOREIGN KEY(funding_id) REFERENCES campaign_funding(id),CHECK(status IN ('AUTHORIZED','CAPTURED','FAILED'))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS campaign_payment_events (
 event_id VARCHAR(100) PRIMARY KEY,body_hash CHAR(64) NOT NULL,funding_id CHAR(36) NOT NULL,
 event_type VARCHAR(40) NOT NULL,created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(funding_id) REFERENCES campaign_funding(id)
) ENGINE=InnoDB;
