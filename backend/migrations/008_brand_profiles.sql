CREATE TABLE IF NOT EXISTS brand_profiles (
  brand_id CHAR(36) PRIMARY KEY,
  details JSON NOT NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 0,
  logo_revision INT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CONSTRAINT fk_brand_profile_brand FOREIGN KEY(brand_id) REFERENCES brands(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS brand_logos (
  brand_id CHAR(36) PRIMARY KEY,
  image MEDIUMBLOB NOT NULL,
  mime_type VARCHAR(32) NOT NULL,
  content_hash CHAR(64) NOT NULL,
  byte_size INT UNSIGNED NOT NULL,
  width SMALLINT UNSIGNED NOT NULL,
  height SMALLINT UNSIGNED NOT NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CONSTRAINT fk_brand_logo_brand FOREIGN KEY(brand_id) REFERENCES brands(id) ON DELETE CASCADE
) ENGINE=InnoDB;
